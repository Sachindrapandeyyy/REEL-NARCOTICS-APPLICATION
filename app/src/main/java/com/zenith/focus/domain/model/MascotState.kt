package com.zenith.focus.domain.model

enum class MascotState {
    HEALTHY,    // Normal happy state, sparkling eyes
    FOCUSED,    // Meditating calmly during active lock
    ALERT,      // Vigilant state watching out for distractions
    PROTECTED,  // Shield active, safe from impulses
    BLOCKING,   // Actively repelling a short-form feed or adult content
    STREAK,     // Celebrating multi-day focus milestone
    RECOVERY    // Restful state when regaining focus
}
